def load_search(name):
    path = os.path.join(SEARCH, f"{name}.json")
    if not os.path.exists(path):
        return []
    try:
        with open(path) as f:
            data = json.load(f)
        if data.get("success") and data.get("results"):
            return [r["original_url"] for r in data["results"] if r.get("original_url")]
    except Exception as e:
        print(f"WARN {name}: {e}")
    return []

def atmos_exists(fname):
    return os.path.exists(os.path.join(ATMOS, fname))

lines = ["// AUTO-GENERATED by scripts/build_images_manifest.py — do not edit by hand",
         "// IMG: web-search photos + atmosphere assets. GEN: AI-generated studio product shots.",
         ""]
lines.append("export const IMG = {")
for key, (search_name, fallback) in GROUPS.items():
    urls = load_search(search_name)
    if not urls and atmos_exists(fallback):
        urls = [f"/atmosphere/{fallback}"]
    if not urls and atmos_exists("hero-laptop.png"):
        urls = ["/atmosphere/hero-laptop.png"]
    lines.append(f"  {key}: [")
    for u in urls:
        lines.append(f'    "{u}",')
    lines.append("  ],")
lines.append("")
for key, fname in ATMOS_FILES.items():
    if atmos_exists(fname):
        lines.append(f'  {key}: "/atmosphere/{fname}",')
    elif atmos_exists("hero-laptop.png"):
        lines.append(f'  {key}: "/atmosphere/hero-laptop.png",')
lines.append("};")
lines.append("")

lines.append("export const GEN = {")
for key, fname in GEN_FILES.items():
    if os.path.exists(os.path.join(PRODS, fname)):
        lines.append(f'  {key}: "/products/{fname}",')
lines.append("};")
lines.append("")

with open(OUT, "w") as f:
    f.write("\n".join(lines))
print(f"Wrote {OUT}")
